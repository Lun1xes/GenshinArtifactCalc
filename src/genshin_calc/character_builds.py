def find_build_for_character(char_or_key: str) -> Optional[CharacterBuild]:
    """Find the best matching CharacterBuild given a character name, GOOD location key, or display name."""
    if not char_or_key or char_or_key in ("(Выбрать персонажа...)", "Не выбран (по роли)"):
        return None

    # 1. Exact display name match
    for b in CHARACTER_BUILDS:
        if b.display_name == char_or_key:
            return b

    # 2. Check CHARACTER_KEY_MAP
    canonical = CHARACTER_KEY_MAP.get(char_or_key)

    # 3. Match by name
    target = canonical or char_or_key
    target_clean = target.strip().lower().replace(" ", "").replace("_", "").replace("ё", "е")

    for b in CHARACTER_BUILDS:
        build_clean = b.name.strip().lower().replace(" ", "").replace("_", "").replace("ё", "е")
        if target_clean == build_clean or target_clean in build_clean or build_clean in target_clean:
            return b

    return None


