def format_weapon_name(weapon_id: str) -> str:
    """Translate or format weapon ID into readable name."""
    clean = weapon_id.lower().replace("-", "_").strip()
    if clean in WEAPON_NAMES_RU:
        return WEAPON_NAMES_RU[clean]
    return clean.replace("_", " ").title()


@dataclass
class CharacterBuild:
    name: str                       # e.g. "Фурина"
    build_name: str                 # e.g. "Sub-DPS / Буфер"
    element: str                    # e.g. "Гидро"
    role: str                       # e.g. "Sub-DPS"
    best_sets: list[str]            # Russian names of artifact sets
    good_set_keys: list[str]        # GOOD format set keys
    main_stats: dict[str, list[str]] # slot -> list of recommended main stats
    substat_weights: dict[str, float] # substat name -> weight (0.0 to 2.0)
    notes: str = ""                 # e.g. "Требует 160-200% ВЭ. Атака не нужна."
    weapons: list[dict] = field(default_factory=list)

    @property
    def display_name(self) -> str:
        return f"{self.name} ({self.build_name})"

    @property
    def top_weapon_names(self) -> list[str]:
        names = []
        for w in self.weapons:
            wid = w.get("id", "") if isinstance(w, dict) else str(w)
            if wid:
                names.append(format_weapon_name(wid))
        return names


