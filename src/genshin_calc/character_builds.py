@dataclass
class CompatibilityResult:
    build: CharacterBuild
    score: float                    # 0 to 100%
    is_ideal: bool                  # Perfect match (set + slot + main + high subs)
    set_matches: bool               # Does the artifact set match the build?
    main_stat_matches: bool         # Is main stat in recommended list for this slot?
    verdict: str                    # e.g. "⭐ Идеально", "✅ Отлично", "⚠️ Сомнительно", "❌ Не подходит"
    explanation: str                # Human-readable breakdown in Russian


def evaluate_artifact_for_build(
    build: CharacterBuild,
    slot: str,
    main_stat: str,
    substats: dict[str, Any],
    set_name_or_key: str = "",
) -> CompatibilityResult:
    """Evaluate how well an artifact matches a specific character build."""
    set_matches = False
    if set_name_or_key:
        key = SET_NAME_TO_KEY.get(set_name_or_key, set_name_or_key)
        name_ru = ARTIFACT_SETS.get(key, {}).get("name_ru", set_name_or_key)
        set_matches = (key in build.good_set_keys or name_ru in build.best_sets)

    # 1. Main stat check
    # Flowers always have HP, Plumes always have ATK
    rec_mains = build.main_stats.get(slot, [])
    if slot in ("Цветок жизни", "Перо смерти"):
        main_matches = True
    else:
        main_matches = any(m.lower() == main_stat.lower() for m in rec_mains)

    # 2. Substat usefulness check
    total_weights = 0.0
    valuable_subs = []
    useless_subs = []

    for sub_name in substats.keys():
        w = build.substat_weights.get(sub_name, 0.0)
        total_weights += max(0.0, w)
        if w >= 1.0:
            valuable_subs.append(sub_name)
        elif w <= 0.0:
            useless_subs.append(sub_name)

    # Max possible substat weight sum for 4 stats (assuming 2.0 + 2.0 + 1.5 + 1.5 = ~7.0)
    sub_score = min(total_weights / 6.0, 1.0) * 100.0

    # 3. Overall score calculation
    if not main_matches:
        # If main stat does NOT match on Sands/Goblet/Circlet, penalty is massive
        overall_score = sub_score * 0.25
        verdict = "❌ Не подходит"
        recs_str = " / ".join(rec_mains)
        explanation = f"Главный стат «{main_stat}» не подходит. Для {build.name} здесь нужно: {recs_str}."
        is_ideal = False
    else:
        multiplier = 1.0 if set_matches else 0.85
        overall_score = sub_score * multiplier
        if overall_score >= 80.0 and set_matches:
            verdict = "⭐ Идеально"
            explanation = f"Родной сет ({build.best_sets[0]}), правильный главный стат ({main_stat}) и полезные сабстаты ({', '.join(valuable_subs) or 'все'})."
            is_ideal = True
        elif overall_score >= 60.0:
            verdict = "✅ Отлично"
            set_note = "родной сет" if set_matches else "универсальный кусок (оффсет)"
            explanation = f"Хорошо подходит ({set_note}), верный стат «{main_stat}»."
            is_ideal = False
        elif overall_score >= 40.0:
            verdict = "⚠️ Приемлемо"
            explanation = f"Главный стат верный, но мало полезных сабстатов для {build.name}."
            is_ideal = False
        else:
            verdict = "⚠️ Слабо"
            explanation = f"Много мёртвых статов ({', '.join(useless_subs)}), мало ценности для {build.name}."
            is_ideal = False

    return CompatibilityResult(
        build=build,
        score=round(overall_score, 1),
        is_ideal=is_ideal,
        set_matches=set_matches,
        main_stat_matches=main_matches,
        verdict=verdict,
        explanation=explanation,
    )


def find_top_characters_for_artifact(
    slot: str,
    main_stat: str,
    substats: dict[str, Any],
    set_name_or_key: str = "",
    limit: int = 4,
) -> list[CompatibilityResult]:
    """Analyze all character builds and return the top compatible characters."""
    results: list[CompatibilityResult] = []

    for b in CHARACTER_BUILDS:
        res = evaluate_artifact_for_build(
            build=b,
            slot=slot,
            main_stat=main_stat,
            substats=substats,
            set_name_or_key=set_name_or_key,
        )
        results.append(res)

    # Sort: set matches first, then highest score
    results.sort(key=lambda r: (r.set_matches, r.score), reverse=True)
    return results[:limit]


def _load_external_data() -> None:
    """Seamlessly load and merge external data from data/*.json if present."""
    from .utils import get_project_root
    data_dir = os.path.join(get_project_root(), "data")
    if not os.path.isdir(data_dir):
        return

    # 1. Merge Artifact Sets
    arts_file = os.path.join(data_dir, "artifacts_ru.json")
    if os.path.isfile(arts_file):
        try:
            with open(arts_file, "r", encoding="utf-8") as f:
                arts_data = json.load(f)
            lower_existing = {k.lower(): k for k in ARTIFACT_SETS}
            for k, v in arts_data.items():
                canonical_k = lower_existing.get(k.lower(), k)
                if canonical_k not in ARTIFACT_SETS:
                    ARTIFACT_SETS[canonical_k] = {
                        "name_ru": v.get("name_ru", canonical_k),
                        "description": v.get("description", ""),
                    }
                    lower_existing[canonical_k.lower()] = canonical_k
                else:
                    if not ARTIFACT_SETS[canonical_k].get("name_ru"):
                        ARTIFACT_SETS[canonical_k]["name_ru"] = v.get("name_ru", canonical_k)
            for k, v in ARTIFACT_SETS.items():
                name_ru = v.get("name_ru")
                if name_ru and name_ru not in SET_NAME_TO_KEY:
                    SET_NAME_TO_KEY[name_ru] = k
        except Exception:
            pass

    # 2. Merge Character Metadata & Key Map
    chars_file = os.path.join(data_dir, "characters_meta.json")
    if os.path.isfile(chars_file):
        try:
            with open(chars_file, "r", encoding="utf-8") as f:
                chars_meta = json.load(f)
            for char_id, meta in chars_meta.items():
                name_ru = meta.get("name_ru")
                name_en = meta.get("name_en")
                if name_ru:
                    CHARACTER_KEY_MAP[char_id] = name_ru
                    if name_en:
                        CHARACTER_KEY_MAP[name_en] = name_ru
                        clean_en = name_en.replace(" ", "").replace("-", "").replace("'", "")
                        CHARACTER_KEY_MAP[clean_en] = name_ru
        except Exception:
            pass

    # 3. Merge Character Builds
    builds_file = os.path.join(data_dir, "builds.json")
    if os.path.isfile(builds_file):
        try:
            with open(builds_file, "r", encoding="utf-8") as f:
                builds_data = json.load(f)

            existing_char_names = {b.name for b in CHARACTER_BUILDS}
            existing_display_names = {b.display_name for b in CHARACTER_BUILDS}

            for item in builds_data:
                char_name = item.get("name")
                if not char_name:
                    continue

                item_weapons = item.get("weapons", [])
                if item_weapons:
                    for b in CHARACTER_BUILDS:
                        if b.name == char_name and not b.weapons:
                            b.weapons = item_weapons

                role_name = item.get("build_name", item.get("role", "DPS"))
                display = f"{char_name} ({role_name})"
                if display in existing_display_names:
                    continue

                if char_name in existing_char_names:
                    # Keep handcrafted priority for existing characters unless distinct role
                    if any(b.name == char_name and role_name.lower() in b.build_name.lower() for b in CHARACTER_BUILDS):
                        continue

                new_build = CharacterBuild(
                    name=char_name,
                    build_name=role_name,
                    element=item.get("element", "Анемо"),
                    role=item.get("role", "DPS"),
                    best_sets=item.get("best_sets", ["Золотая труппа"]),
                    good_set_keys=item.get("good_set_keys", ["GoldenTroupe"]),
                    main_stats=item.get("main_stats", {}),
                    substat_weights=item.get("substat_weights", {}),
                    notes=item.get("notes", ""),
                    weapons=item_weapons,
                )
                CHARACTER_BUILDS.append(new_build)
                existing_display_names.add(display)
        except Exception:
            pass


# Automatically load external data on import
_load_external_data()

